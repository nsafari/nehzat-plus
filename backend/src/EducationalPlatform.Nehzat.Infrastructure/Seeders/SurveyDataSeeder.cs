    public async Task SeedAsync()
    {
        if (await _db.IssueSurveys.AnyAsync<IssueSurvey>())
            return;

        // Ensure a default admin user exists for the foreign key
        var adminUser = await _db.Users.FirstOrDefaultAsync(u => u.Username == "admin");
        if (adminUser == null)
        {
            adminUser = new User
            {
                Username = "admin",
                FirstName = "مدیر",
                LastName = "سیستم",
                Email = "admin@nehzat128.ir",
                ApprovalStatus = "approved",
                UserType = "admin",
                CreatedAt = DateTime.UtcNow,
                UpdatedAt = DateTime.UtcNow,
            };
            _db.Users.Add(adminUser);
            await _db.SaveChangesAsync();
        }

        var categories = new[]
        {
            ("والدین و خانواده", ParentFamilyQuestions()),
            ("سازماندهی و مستندسازی", OrganizationQuestions()),
            ("منابع مالی و مشاوره", FinancialQuestions()),
            ("آموزشی", EducationalQuestions()),
            ("فرهنگی", CulturalQuestions()),
            ("خط و خوشنویسی", CalligraphyQuestions()),
            ("ارتباطات", CommunicationsQuestions()),
            ("معلمان", TeachersQuestions()),
            ("آموزجوها", TraineesQuestions()),
            ("متفرقه", MiscellaneousQuestions()),
        };

        var survey = new IssueSurvey
        {
            Title = "نظرسنجی جامع مسائل مکتب",
            Description = "نظرسنجی جامع برای ارزیابی مسائل مکتب از دیدگاه متربیان و آموزجوها",
            SurveyType = "general",
            TargetRole = "all",
            Status = "closed",
            StartDate = new DateTime(2026, 7, 1),
            EndDate = new DateTime(2026, 7, 31),
            IsAnonymous = true,
            ScoreScaleMin = 1,
            ScoreScaleMax = 5,
            CreatedById = adminUser.Id,
            CreatedAt = DateTime.UtcNow,
            UpdatedAt = DateTime.UtcNow,
        };

        _db.IssueSurveys.Add(survey);
        await _db.SaveChangesAsync();

        var questionId = 1;
        foreach (var (category, questions) in categories)
        {
            for (int i = 0; i < questions.Count; i++)
            {
                var question = new IssueSurveyQuestion
                {
                    SurveyId = survey.Id,
                    QuestionText = questions[i],
                    Category = category,
                    SubCategory = string.Empty,
                    TargetAudience = "متربی",
                    SortOrder = i,
                    IsActive = true,
                    CreatedAt = DateTime.UtcNow,
                };
                _db.IssueSurveyQuestions.Add(question);
                questionId++;
            }
        }

        await _db.SaveChangesAsync();

        var respondents = new[]
        {
            "علی احمدی", "فاطمه محمدی", "محمد رضایی", "مریم کریمی", "رضا حسینی",
            "زهرا علیپور", "امیرحسین نوری", "سارا موسوی", "مهدی کریمی", "نیلوفر احمدی",
            "امیرمهدی رضایی", "شیرین محمدی", "کیانوش طاهری", "مریم احمدی", "سجاد کریمی",
            "فاطمه موسوی", "رضا محمدی", "مهسا کریمی", "امیرحسین مهدوی", "زهرا نوری",
            "مریم حسینی", "امیررضا موسوی", "سارا علیپور", "مهدی احمدی", "نیلوفر کریمی",
            "کیانوش احمدی"
        };

        var rng = new Random(42);
        var responses = new List<IssueSurveyResponse>();
        var comments = new List<IssueSurveyComment>();

        for (int r = 0; r < respondents.Length; r++)
        {
            var respondentId = r + 1;
            var respondentName = respondents[r];

            var questionIds = Enumerable.Range(0, 184).Select(i => i + 1).ToList();
            var sampledQuestions = questionIds.OrderBy(_ => rng.Next()).Take(130).ToList();

            foreach (var qId in sampledQuestions)
            {
                responses.Add(new IssueSurveyResponse
                {
                    SurveyId = survey.Id,
                    QuestionId = qId,
                    RespondentId = null,
                    RespondentRole = "student",
                    RespondentBranchId = null,
                    Score = rng.Next(1, 6),
                    AnsweredAt = DateTime.UtcNow,
                });
            }

            if (r < 5)
            {
                var commentTexts = new[]
                {
                    "نظرسنجی بسیار مفید و بینش‌آور بود.",
                    "توصیه می‌کنم سال‌های بعد ادامه یابد.",
                    "نیاز به بهبود در بخش زیرساخت هستند.",
                    "از کیفیت آموزش راضی هستم.",
                    "پیشنهاد تغییر برنامه درسی برای بهبود."
                };
                comments.Add(new IssueSurveyComment
                {
                    SurveyId = survey.Id,
                    RespondentId = null,
                    Comment = commentTexts[r % commentTexts.Length],
                    IsPublic = true,
                    CreatedAt = DateTime.UtcNow,
                });
            }
        }

        foreach (var response in responses)
        {
            _db.IssueSurveyResponses.Add(response);
        }

        foreach (var comment in comments)
        {
            _db.IssueSurveyComments.Add(comment);
        }

        await _db.SaveChangesAsync();
    }

