    {
        return $"""
            بخش: مقدمه
            این ماژول به موضوع «{title}» می‌پردازد و جزئی از نظام تربیت مربی (NTM) است.

            بخش: اهداف یادگیری
            - آشنایی با مفاهیم پایه‌ای {title}
            - درک عمیق از {description}
            - توانایی کاربرد مفاهیم در محیط آموزشی واقعی

            فصل: محتوای اصلی
            این بخش شامل ارائه نظری، مثال‌های عملی و تمرین‌های گروهی است.
            مربی باید با استفاده از روش‌های تدریس فعال، مشارکت حداکثری شرکت‌کنندگان را جلب کند.

            سؤال: پرسش تأملی
