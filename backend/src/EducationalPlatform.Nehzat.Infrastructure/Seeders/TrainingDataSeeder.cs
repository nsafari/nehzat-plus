    private TrainingStage AddStage(int courseId, string title, int order, bool required, DateTime now, string description)
    {
        var stage = new TrainingStage
        {
            CourseId = courseId,
            Title = title,
            StageOrder = order,
            Required = required,
            Description = description,
            CreatedAt = now
        };
        _db.TrainingStages.Add(stage);
        _db.SaveChanges();
        return stage;
    }

    private void AddSessionsForAxis(int stageId, string prefix, (string title, string description, int duration)[] modules, DateTime now)
    {
        for (int i = 0; i < modules.Length; i++)
        {
            var session = new TrainingSession
            {
                StageId = stageId,
                Title = modules[i].title,
                SessionNumber = i + 1,
                DurationMinutes = modules[i].duration,
                SessionType = modules[i].duration >= 90 ? "workshop" : "theory",
                Description = modules[i].description,
                CreatedAt = now
            };
            _db.TrainingSessions.Add(session);
            _db.SaveChanges();

            // Add content for each session
            var content = new TrainingContent
            {
                SessionId = session.Id,
                ContentType = "transcript",
                SourceFile = $"/content/ntm/{prefix}{i + 1}.json",
                RawText = GenerateSessionContent(modules[i].title, modules[i].description),
                ImportedAt = now
            };
            _db.TrainingContents.Add(content);
        }
        _db.SaveChanges();
    }

